export function activeMoneyCards(chart: NatalChart): MoneyCard[] {
  return MONEY_CARDS.filter((card) => card.matches(chart)).sort((a, b) => a.order - b.order);
}

export function hasCompleteIlyaSet(chart: NatalChart): boolean {
  return ["house-sign:2:capricorn", "house-sign:8:cancer", "ruler-house:5:venus:9"].every((key) =>
    activeMoneyCards(chart).some((card) => card.key === key),
  );
}
