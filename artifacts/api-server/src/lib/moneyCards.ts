import type { NatalChart } from "./astrology";

export type MoneyCardKind =
  | "house"
  | "house-sign"
  | "planet-house"
  | "ruler-house"
  | "summary";

export type MoneyCard = {
  key: string;
  order: number;
  kind: MoneyCardKind;
  house: 2 | 5 | 8 | 11;
  title: string;
  paragraphs: string[];
  signKey?: string;
  planetKey?: string;
  rulerKey?: string;
  planetHouse?: number;
  rulerHouse?: number;
  matches: (chart: NatalChart) => boolean;
};

const houseSign = (chart: NatalChart, house: number) =>
  chart.houses.find((item) => item.number === house)?.signKey;

const bodyHouse = (chart: NatalChart, planet: string) =>
  chart.bodies.find((item) => item.key === planet)?.house;

const rulers: Record<string, string[]> = {
  aries: ["mars"], taurus: ["venus"], gemini: ["mercury"], cancer: ["moon"],
  leo: ["sun"], virgo: ["mercury"], libra: ["venus"], scorpio: ["mars", "pluto"],
  sagittarius: ["jupiter"], capricorn: ["saturn"], aquarius: ["saturn", "uranus"],
  pisces: ["jupiter", "neptune"],
};

const houseRulers = (chart: NatalChart, house: number) => rulers[houseSign(chart, house) ?? ""] ?? [];

