function aspectSentence(aspect: Aspect): string {
  switch (aspect) {
    case "conjunction":
      return "Соединение усиливает тему обоих факторов и делает её заметнее в текущих делах.";
    case "sextile":
      return "Секстиль открывает возможность развить эту тему через собственное действие и внимательное использование обстоятельств.";
    case "trine":
      return "Тригон поддерживает естественное раскрытие этой темы и помогает использовать её без лишнего давления.";
    case "square":
      return "Квадрат показывает напряжение между двумя способами действовать и просит найти более устойчивое решение.";
    case "opposition":
      return "Оппозиция проявляет тему через взаимодействие с людьми или обстоятельствами и предлагает учесть обе стороны.";
  }
}

